"""Export the graph as a Cypher script for Neo4j.

The query service runs on the in-memory store, but the schema uses Neo4j's
conventions (labels, UPPER_SNAKE relationship types, property maps), so the
same graph loads into Neo4j unchanged. Every statement is a MERGE, so the
script is idempotent and can be re-run after a dataset update.
"""

from __future__ import annotations

import json

from skillgraph.graph.store import NetworkXStore


def _props(data: dict) -> str:
    clean = {k: v for k, v in data.items() if k != "label" and v is not None}
    items = []
    for key, value in sorted(clean.items()):
        items.append(f"`{key}`: {json.dumps(value, ensure_ascii=False)}")
    return "{" + ", ".join(items) + "}"


def to_cypher(store: NetworkXStore) -> str:
    lines = ["// Generated by `skillgraph export-cypher`. Idempotent: safe to re-run.", ""]
    labels = sorted({d["label"] for _, d in store.g.nodes(data=True)})
    for label in labels:
        lines.append(f"CREATE CONSTRAINT {label.lower()}_id IF NOT EXISTS FOR (n:{label}) REQUIRE n.id IS UNIQUE;")
    lines.append("")
    for node_id, data in sorted(store.g.nodes(data=True)):
        lines.append(f"MERGE (n:{data['label']} {{id: {json.dumps(node_id)}}}) SET n += {_props(data)};")
    lines.append("")
    for u, v, data in store.g.edges(data=True):
        rel = data["type"]
        props = {k: val for k, val in data.items() if k != "type" and val is not None}
        set_clause = f" SET r += {_props(props)}" if props else ""
        la, lb = store.g.nodes[u]["label"], store.g.nodes[v]["label"]
        # labelled MATCH so Neo4j uses the uniqueness index instead of a full scan
        lines.append(f"MATCH (a:{la} {{id: {json.dumps(u)}}}), (b:{lb} {{id: {json.dumps(v)}}}) "
                     f"MERGE (a)-[r:{rel}]->(b){set_clause};")
    return "\n".join(lines) + "\n"
